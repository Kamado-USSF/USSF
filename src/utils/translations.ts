export const getTranslation = (langCode: string, key: string): string => {
  if (CORE_DICTIONARY[langCode] && CORE_DICTIONARY[langCode][key]) {
    return CORE_DICTIONARY[langCode][key];
  }
  // Fallback to English
  return CORE_DICTIONARY.en[key] || key;
};

// Applies RTL / LTR and initializes full-page translation
export const applyLanguageToDocument = (langCode: string) => {
  if (typeof document === 'undefined') return;
  const isRTL = ['ar', 'he', 'fa', 'ur'].includes(langCode);
  document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
  document.documentElement.lang = langCode;
  try {
    localStorage.setItem('ussf_language', langCode);
  } catch (e) {
    // Ignore storage errors
  }
};
